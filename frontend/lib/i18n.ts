export type TKey = keyof typeof vi;

export const messages: Record<Lang, Record<TKey, string>> = { vi, en };

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let text = messages[lang][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

export function useT(): (key: TKey, vars?: Record<string, string | number>) => string {
  const lang = useSettingsStore((s) => s.settings.lang);
  return (key, vars) => translate(lang, key, vars);
}
